/**
 * Resolves a free-text GitHub profile location to a known city/country entry.
 * Unresolvable strings ("remote", "Metaverse", empty) return null and are skipped.
 *
 * @param location - Raw `location` string from a GitHub user profile.
 * @returns The matched geo entry, or null when nothing in the table matches.
 * @example
 * geocodeLocation("Port Harcourt, Rivers State, Nigeria")?.label; // "Port Harcourt"
 */
export const geocodeLocation = (location: string | null | undefined): GeoEntry | null => {
  if (!location) return null;
  const normalized = location.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase();
  return TABLE.find((entry) => normalized.includes(entry.key)) ?? null;
};
